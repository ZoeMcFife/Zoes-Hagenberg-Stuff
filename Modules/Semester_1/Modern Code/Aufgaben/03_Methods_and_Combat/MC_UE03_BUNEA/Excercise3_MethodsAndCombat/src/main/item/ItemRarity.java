package main.item;

/**
 * Enumeration representing the rarity levels of items in the game.
 * Higher rarity items are generally more powerful and valuable.
 */
public enum ItemRarity
{
    /** Common items with basic stats */
    LOW,
    
    /** Uncommon items with moderate stats */
    MEDIUM,
    
    /** Rare items with strong stats */
    HIGH,
    
    /** Extremely rare and powerful items */
    LEGENDARY
}
