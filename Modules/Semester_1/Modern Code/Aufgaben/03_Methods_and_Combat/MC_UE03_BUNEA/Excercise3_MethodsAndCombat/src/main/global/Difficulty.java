package main.global;

/**
 * Enumeration representing game difficulty levels.
 * Affects enemy spawn rates and combat parameters.
 */
public enum Difficulty
{
    /** Easy difficulty with slower difficulty scaling */
    EASY,
    
    /** Medium difficulty with moderate difficulty scaling */
    MEDIUM,
    
    /** Hard difficulty with rapid difficulty scaling */
    HARD,
    
    /** No difficulty selected */
    NONE
}
